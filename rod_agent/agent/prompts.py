def system_prompt(mode: str, fmt: str = "") -> list[dict]:
    """고정 부분(캐시 대상)과 가변 부분을 나눠 system 블록 목록으로 만든다."""
    m = MODES.get(mode, MODES["auto"])
    fmt = fmt or m["format"]
    extra = f"# 현재 업무 모드: {m['label']}\n{m['guide']}\n"
    if fmt in FORMAT_HINT:
        extra += FORMAT_HINT[fmt] + "\n"
    extra += f"오늘 날짜: {date.today():%Y-%m-%d}"
    return [
        {"type": "text", "text": BASE_PROMPT, "cache_control": {"type": "ephemeral"}},
        {"type": "text", "text": extra},
    ]


def public_modes() -> list[dict]:
    return [
        {"id": k, "label": v["label"], "icon": v["icon"], "format": v["format"], "examples": v["examples"]}
        for k, v in MODES.items()
    ]
